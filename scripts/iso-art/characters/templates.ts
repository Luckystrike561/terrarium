/**
 * Head templates shared by every worker sheet: faces and hair, from the
 * front and from the back. The body is drawn from joints instead. Letters
 * are looked up in the worker's palette, and `.` and space are
 * transparent.
 *
 * Legend: o outline, s/S/r skin light/shade/deep, w eye white, e pupil,
 * h/H/d hair base/light/dark.
 *
 * Every template is HEAD_TEMPLATE_WIDTH wide and shares one origin, so a
 * face, a hairstyle and an accessory stamped at the same point line up.
 */

export const HEAD_TEMPLATE_WIDTH = 24;
